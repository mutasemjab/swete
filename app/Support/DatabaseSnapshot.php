<?php

namespace App\Support;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use RuntimeException;

/** Data-only deployment snapshot. Schema always comes from the application's migrations. */
class DatabaseSnapshot
{
    private const EXCLUDED = [
        'migrations', 'password_resets', 'password_reset_tokens', 'sessions', 'cache', 'cache_locks',
        'jobs', 'job_batches', 'failed_jobs', 'personal_access_tokens',
        'oauth_auth_codes', 'oauth_access_tokens', 'oauth_refresh_tokens',
    ];

    public static function path(): string
    {
        return database_path('seeders/data/current-database.php');
    }

    public function capture(): array
    {
        return DB::transaction(function () {
            $tables = [];
            foreach (array_diff($this->tableNames(), self::EXCLUDED) as $table) {
                $columns = Schema::getColumnListing($table);
                $rows = $this->rows($table, $columns);
                $tables[$table] = ['columns' => $columns, 'rows' => $rows, 'sha256' => $this->fingerprint($rows)];
            }

            return [
                'version' => 1,
                'driver' => DB::connection()->getDriverName(),
                'exported_at' => now('Asia/Amman')->toIso8601String(),
                'tables' => $tables,
            ];
        });
    }

    public function write(array $snapshot, string $path): void
    {
        $json = json_encode($snapshot, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
        $compressed = gzencode($json, 9);
        if ($compressed === false) {
            throw new RuntimeException('Could not compress the database snapshot.');
        }
        $payload = ['sha256' => hash('sha256', $json), 'data' => base64_encode($compressed)];
        $php = "<?php\n\n// Generated by php artisan database:export-seed. Contains application data and password hashes.\nreturn ".var_export($payload, true).";\n";
        $directory = dirname($path);
        if (! is_dir($directory) && ! mkdir($directory, 0755, true) && ! is_dir($directory)) {
            throw new RuntimeException('Could not create the snapshot directory.');
        }
        $temporary = tempnam($directory, '.snapshot-');
        try {
            if ($temporary === false || file_put_contents($temporary, $php, LOCK_EX) === false || ! rename($temporary, $path)) {
                throw new RuntimeException('Could not write the database snapshot.');
            }
        } finally {
            if ($temporary && is_file($temporary)) {
                unlink($temporary);
            }
        }
    }

    public function read(string $path): array
    {
        if (! is_file($path)) {
            throw new RuntimeException('Database snapshot missing. Include database/seeders/data/current-database.php in the deployment.');
        }
        $payload = require $path;
        $compressed = base64_decode($payload['data'] ?? '', true);
        $json = $compressed === false ? false : @gzdecode($compressed);
        if ($json === false || ! hash_equals($payload['sha256'] ?? '', hash('sha256', $json))) {
            throw new RuntimeException('Database snapshot checksum mismatch.');
        }

        return json_decode($json, true, 512, JSON_THROW_ON_ERROR);
    }

    /** Returns false when this exact snapshot is already installed; never overwrites existing data. */
    public function restore(array $snapshot): bool
    {
        if (($snapshot['version'] ?? null) !== 1 || ($snapshot['driver'] ?? null) !== DB::connection()->getDriverName()
            || empty($snapshot['tables']) || ! is_array($snapshot['tables'])) {
            throw new RuntimeException('Unsupported database snapshot format or database driver.');
        }

        $existingTables = $this->tableNames();
        foreach ($snapshot['tables'] as $table => $data) {
            if (! in_array($table, $existingTables, true) || in_array($table, self::EXCLUDED, true)) {
                throw new RuntimeException("Snapshot table {$table} is unavailable. Run the application migrations first.");
            }
            $columns = Schema::getColumnListing($table);
            if (array_diff($columns, $data['columns']) || array_diff($data['columns'], $columns)) {
                throw new RuntimeException("Snapshot schema does not match table {$table}.");
            }
            if (! hash_equals($data['sha256'], $this->fingerprint($data['rows']))) {
                throw new RuntimeException("Snapshot data checksum mismatch for {$table}.");
            }
        }

        $populated = array_filter(array_diff($existingTables, ['migrations']), fn ($table) => DB::table($table)->exists());
        if ($populated) {
            if (! array_diff($populated, array_keys($snapshot['tables'])) && $this->matches($snapshot)) {
                return false;
            }
            throw new RuntimeException('The destination database already contains data. This deployment seeder requires an empty migrated database and will not replace or merge existing records.');
        }

        // The schema contains circular references. Restore their original IDs atomically,
        // then restore FK enforcement even when an insert or verification fails.
        Schema::disableForeignKeyConstraints();
        try {
            DB::transaction(function () use ($snapshot) {
                foreach ($snapshot['tables'] as $table => $data) {
                    $batchSize = min(200, max(1, intdiv(900, count($data['columns']))));
                    foreach (array_chunk($data['rows'], $batchSize) as $rows) {
                        DB::table($table)->insert($rows);
                    }
                }
                if (! $this->matches($snapshot)) {
                    throw new RuntimeException('Restored data did not match the snapshot; all inserts have been rolled back.');
                }
            });
        } finally {
            Schema::enableForeignKeyConstraints();
        }

        return true;
    }

    public function matches(array $snapshot): bool
    {
        foreach ($snapshot['tables'] as $table => $data) {
            if (! hash_equals($data['sha256'], $this->fingerprint($this->rows($table, $data['columns'])))) {
                return false;
            }
        }

        return true;
    }

    private function tableNames(): array
    {
        $tables = match (DB::connection()->getDriverName()) {
            'mysql' => DB::select("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'"),
            'sqlite' => DB::select("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'"),
            default => throw new RuntimeException('Database snapshots support MySQL/MariaDB and SQLite.'),
        };
        $names = array_map(fn ($table) => array_values((array) $table)[0], $tables);
        sort($names);

        return $names;
    }

    private function rows(string $table, array $columns): array
    {
        return DB::table($table)->select($columns)->get()->map(function ($record) {
            $row = [];
            foreach ((array) $record as $column => $value) {
                // Keep password hashes, but do not transfer active remember-me sessions.
                $row[$column] = $column === 'remember_token' || $value === null ? null : (string) $value;
            }
            return $row;
        })->all();
    }

    private function fingerprint(array $rows): string
    {
        $serialized = array_map(function ($row) {
            ksort($row);
            return json_encode($row, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
        }, $rows);
        sort($serialized, SORT_STRING);

        return hash('sha256', implode("\n", $serialized));
    }
}
